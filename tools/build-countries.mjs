#!/usr/bin/env node
/*
 * build-countries.mjs — the partner directory's country names, in every language.
 *
 * The directory is exported from somewhere else and its `country` field is
 * English, inconsistently: `USA`, `MEXICO`, `Utd.Arab.Emir.`. The locator groups
 * its filter dropdown by that value and prints it on every card, so a French
 * visitor read a list of English country names with two of them misspelled.
 *
 * Rather than translate 82 names by hand — and get them wrong, and have to do it
 * again next year — the export's spellings are mapped to ISO 3166-1 codes once,
 * and the names come from `Intl.DisplayNames`. Those are the names the browser
 * itself would use, which is the highest standard available for free.
 *
 * The mapping is the only hand-maintained part, and it is the part that has to
 * be: nothing can infer that `Utd.Arab.Emir.` means AE. Run this again after the
 * export introduces a country, and it will tell you which one it cannot place
 * rather than silently leaving it in English.
 *
 *   node tools/build-countries.mjs
 */
import fs from 'node:fs';
const rows = JSON.parse(fs.readFileSync('content-source/data/partners.json', 'utf8'));
const names = [...new Set(rows.map(r => r.country))].sort();

/* The source export's spellings, mapped to ISO 3166-1 alpha-2. */
const CODES = {
  Albania: 'AL', Algeria: 'DZ', Andorra: 'AD', Argentina: 'AR', Australia: 'AU', Austria: 'AT',
  Bahrain: 'BH', Bangladesh: 'BD', Belgium: 'BE', Bolivia: 'BO', Brazil: 'BR', Bulgaria: 'BG',
  Cameroon: 'CM', Canada: 'CA', Chile: 'CL', China: 'CN', Colombia: 'CO', 'Costa Rica': 'CR',
  Croatia: 'HR', 'Czech Republic': 'CZ', Denmark: 'DK', Ecuador: 'EC', Egypt: 'EG', Finland: 'FI',
  France: 'FR', Germany: 'DE', Greece: 'GR', Guatemala: 'GT', 'Hong Kong': 'HK', Hungary: 'HU',
  India: 'IN', Indonesia: 'ID', Ireland: 'IE', Israel: 'IL', Italy: 'IT', 'Ivory Coast': 'CI',
  Japan: 'JP', Jordan: 'JO', Kazakhstan: 'KZ', Kenya: 'KE', Kuwait: 'KW', Latvia: 'LV',
  Lebanon: 'LB', Luxembourg: 'LU', Malaysia: 'MY', Malta: 'MT', MEXICO: 'MX', Monaco: 'MC',
  Morocco: 'MA', Netherlands: 'NL', Nigeria: 'NG', Norway: 'NO', Oman: 'OM', Pakistan: 'PK',
  Panama: 'PA', Paraguay: 'PY', Peru: 'PE', Philippines: 'PH', Poland: 'PL', Portugal: 'PT',
  Qatar: 'QA', 'Saudi Arabia': 'SA', Senegal: 'SN', Serbia: 'RS', Singapore: 'SG',
  Slovakia: 'SK', Slovenia: 'SI', 'South Africa': 'ZA', 'South Korea': 'KR', Spain: 'ES',
  Sweden: 'SE', Switzerland: 'CH', Taiwan: 'TW', Thailand: 'TH', Tunisia: 'TN', Turkey: 'TR',
  Ukraine: 'UA', 'United Kingdom': 'GB', Uruguay: 'UY', USA: 'US', 'Utd.Arab.Emir.': 'AE',
  Vietnam: 'VN',
};

const missing = names.filter(n => !CODES[n]);
if (missing.length) { console.error('no ISO code for:', missing); process.exit(1); }

const LOCALES = ['fr', 'en', 'de'];
const display = Object.fromEntries(
  LOCALES.map(l => [l, new Intl.DisplayNames([l], { type: 'region' })]),
);

const out = {};
for (const name of names) {
  const code = CODES[name];
  out[name] = { code };
  for (const l of LOCALES) out[name][l] = display[l].of(code);
}
const doc = {
  _comment: [
    'Generated by tools/build-countries.mjs — do not edit by hand.',
    '',
    'The keys are the spellings the partner export uses; do not tidy them, they',
    'are how a row is matched. `code` is ISO 3166-1 alpha-2 and the language keys',
    'come from Intl.DisplayNames.',
  ],
  countries: out,
};
const json = JSON.stringify(doc, null, 2);
fs.writeFileSync('content-source/data/countries.i18n.json', json + String.fromCharCode(10));
console.log(names.length, 'countries');
for (const n of ['USA', 'Germany', 'Utd.Arab.Emir.', 'MEXICO', 'South Korea', 'Ivory Coast', 'United Kingdom']) {
  console.log(' ', n.padEnd(18), JSON.stringify(out[n]));
}
